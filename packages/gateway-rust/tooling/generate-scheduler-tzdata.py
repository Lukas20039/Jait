#!/usr/bin/env python3
"""Pack reviewed IANA 2024a TZif files for the ICU 75.1 scheduler contract.

Preparation source: https://data.iana.org/time-zones/releases/tzdata2024a.tar.gz
SHA-256: 0d0434459acbd2059a7a8da1f3304a84a86591f6ed69c6248fffa502b6edffe3
Compile the release's standard zones + backward (excluding backzone) using zic
-b fat into .jait/artifacts/gateway-rust/scheduler/tzdb-2024a/zoneinfo.
This packer executes no programs and never downloads or updates data implicitly.
"""
from pathlib import Path
import hashlib
import json
import sys

ROOT = Path(__file__).resolve().parents[3]
BASE = ROOT / ".jait/artifacts/gateway-rust/scheduler/tzdb-2024a"
SOURCE = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else BASE / "zoneinfo"
OUTPUT = ROOT / "packages/gateway-rust/src/scheduler"
assert (BASE / "version").read_text().strip() == "2024a"
assert hashlib.sha256((BASE / "tzdata2024a.tar.gz").read_bytes()).hexdigest() == "0d0434459acbd2059a7a8da1f3304a84a86591f6ed69c6248fffa502b6edffe3"
blob = bytearray()
chunks = {}
index = []
for path in sorted(SOURCE.rglob("*")):
    if not path.is_file():
        continue
    name = path.relative_to(SOURCE).as_posix()
    data = path.read_bytes()
    assert data.startswith(b"TZif"), name
    digest = hashlib.sha256(data).hexdigest()
    if digest not in chunks:
        chunks[digest] = (len(blob), len(data))
        blob.extend(data)
    start, size = chunks[digest]
    index.append((name, start, size))
assert len(index) == 597
code = [
    "// Generated by tooling/generate-scheduler-tzdata.py from IANA tzdata 2024a.",
    "// Matches the reference Bun 1.3.10 / ICU 75.1 data contract.",
    'pub const VERSION: &str = "2024a";',
    'pub const DATA: &[u8] = include_bytes!("scheduler-tzdata-2024a.bin");',
    'pub const INDEX: &[(&str, usize, usize)] = &[',
]
code += [f"    ({json.dumps(name)}, {start}, {size})," for name, start, size in index]
code.append("];")
OUTPUT.mkdir(parents=True, exist_ok=True)
(OUTPUT / "tzdata_2024a.rs").write_text("\n".join(code) + "\n")
(OUTPUT / "scheduler-tzdata-2024a.bin").write_bytes(blob)
(OUTPUT / "tzdata-LICENSE").write_bytes((BASE / "LICENSE").read_bytes())
print(json.dumps({"zones": len(index), "unique_tzif": len(chunks), "bytes": len(blob), "sha256": hashlib.sha256(blob).hexdigest()}))
